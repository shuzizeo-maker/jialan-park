// ===================================================================
// 雲霄飛車「速算挑戰」：依年級自動出題，每題限時。
// grade：3～6。回傳格式與上面相同 { q, options（第一個是正確答案）, explain }。
// ===================================================================
export function makeSpeedMath(grade) {
  const r = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
  const pick = arr => arr[Math.floor(Math.random() * arr.length)];
  const near = (ans, spread, fmt = String) => {
    const set = new Set([ans]); let guard = 0;
    while (set.size < 4 && guard++ < 50) {
      const d = pick([-1, 1]) * r(1, spread);
      const v = Math.round((ans + d) * 100) / 100;
      if (v >= 0) set.add(v);
    }
    return [...set].map(fmt);
  };
  const types = {
    3: ['add2', 'sub2', 'times', 'div'],
    4: ['add3', 'sub3', 'times2', 'div2'],
    5: ['times2', 'dec1', 'mixed', 'fracSame'],
    6: ['dec2', 'mixed', 'fracSame', 'percent'],
  }[grade] || ['add2'];
  const kind = pick(types);
  let q, a, opts, explain = '';
  switch (kind) {
    case 'add2': { const x = r(12, 69), y = r(11, 29); a = x + y; q = `${x} + ${y} = ？`; opts = near(a, 10); break; }
    case 'sub2': { const x = r(40, 99), y = r(11, x - 5); a = x - y; q = `${x} − ${y} = ？`; opts = near(a, 10); break; }
    case 'times': { const x = r(2, 9), y = r(2, 9); a = x * y; q = `${x} × ${y} = ？`; opts = near(a, 6); explain = '背熟九九乘法表，速度會更快！'; break; }
    case 'div': { const y = r(2, 9), a0 = r(2, 9); a = a0; q = `${a0 * y} ÷ ${y} = ？`; opts = near(a, 3); break; }
    case 'add3': { const x = r(120, 650), y = r(110, 340); a = x + y; q = `${x} + ${y} = ？`; opts = near(a, 20); break; }
    case 'sub3': { const x = r(400, 999), y = r(101, x - 50); a = x - y; q = `${x} − ${y} = ？`; opts = near(a, 20); break; }
    case 'times2': { const x = r(12, 39), y = r(3, 9); a = x * y; q = `${x} × ${y} = ？`; opts = near(a, 12); break; }
    case 'div2': { const y = r(3, 9), a0 = r(11, 30); a = a0; q = `${a0 * y} ÷ ${y} = ？`; opts = near(a, 4); break; }
    case 'dec1': { const x = r(11, 79) / 10, y = r(11, 59) / 10; a = Math.round((x + y) * 10) / 10; q = `${x} + ${y} = ？`; opts = near(a, 2).map(v => String(Math.round(v * 10) / 10)); break; }
    case 'dec2': { const x = r(2, 9) / 10, y = r(2, 9); a = Math.round(x * y * 10) / 10; q = `${x} × ${y} = ？`; opts = near(a, 2).map(v => String(Math.round(v * 10) / 10)); break; }
    case 'mixed': { const x = r(2, 9), y = r(2, 9), z = r(2, 20); a = z + x * y; q = `${z} + ${x} × ${y} = ？`; opts = [a, (z + x) * y, a + pick([1, 2, 3]), Math.max(0, a - pick([1, 2]))]; opts = [...new Set(opts)].map(String); explain = '先乘除、後加減！'; break; }
    case 'fracSame': {
      const d = r(5, 12), x = r(1, d - 3), y = r(1, d - 1 - x);
      q = `{${x}/${d}} + {${y}/${d}} = ？`;
      const ans = `{${x + y}/${d}}`;
      opts = [ans, `{${x + y}/${d * 2}}`, `{${x + y + 1}/${d}}`, `{${Math.max(1, x + y - 1)}/${d}}`];
      explain = '分母相同，分子相加，分母不變。';
      return { q, options: [...new Set(opts)], explain, timed: true };
    }
    case 'percent': { const p = pick([10, 20, 25, 50, 75]), n = pick([40, 80, 120, 200, 400]); a = n * p / 100; q = `${n} 的 ${p}% 是多少？`; opts = near(a, Math.max(4, a / 4)).map(v => String(Math.round(v))); explain = `${n} × ${p}/100 = ${a}`; break; }
  }
  opts = [...new Set(opts.map(String))];
  if (opts[0] !== String(a)) opts.unshift(String(a));
  while (opts.length < 4) opts.push(String(Number(a) + opts.length * 3));
  return { q, options: [...new Set(opts)].slice(0, 4), explain, timed: true };
}

